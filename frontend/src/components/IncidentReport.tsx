import clsx from 'clsx'
import type { TelemetrySnapshot } from '../types'

interface Props {
  snap: TelemetrySnapshot
}

function fmt(v: number | null, suffix: string, dec = 1) {
  if (v === null || v === undefined) return '—'
  return `${v.toFixed(dec)}${suffix}`
}

function fmtDuration(s: number | null) {
  if (s === null || s === undefined) return '—'
  const m = Math.floor(s / 60)
  const sec = Math.round(s % 60)
  if (m === 0) return `${sec}s`
  return `${m}m ${sec}s`
}

const CC: Record<string, string> = {
  green: 'text-emerald-300 bg-emerald-950/30 border-emerald-800',
  amber: 'text-amber-300 bg-amber-950/30 border-amber-800',
  red: 'text-red-300 bg-red-950/30 border-red-800',
  neutral: 'text-slate-300 bg-navy-800 border-navy-700',
}

export function IncidentReport({ snap }: Props) {
  if (!['RESOLVED', 'RECOVERING'].includes(snap.state)) {
    return (
      <div className="bg-navy-900 border border-navy-700 rounded-lg p-6 text-center">
        <p className="text-slate-500 text-sm">
          Post-incident report will be generated when the incident is resolved.
        </p>
        <p className="text-slate-600 text-xs mt-1">Current state: {snap.state.replace('_', ' ')}</p>
      </div>
    )
  }

  const { peaks, incident_id, scenario_name, detection_time_seconds, recovery_time_seconds, classification, classification_color } = snap

  return (
    <div className="bg-navy-900 border border-navy-700 rounded-lg p-5 space-y-5">
      {/* Header */}
      <div className="flex items-start justify-between">
        <div>
          <h2 className="text-base font-semibold text-white">Post-Incident Report</h2>
          <p className="text-xs text-slate-500 mt-0.5">
            Incident ID: <span className="font-mono text-slate-300">{incident_id}</span>
          </p>
          <p className="text-xs text-slate-600 mt-0.5 italic">Synthetic telemetry — controlled simulation</p>
        </div>
        <span className={clsx(
          'text-xs px-2 py-0.5 rounded border font-semibold',
          snap.state === 'RESOLVED' ? 'bg-emerald-950/30 border-emerald-800 text-emerald-300' : 'bg-sky-950/30 border-sky-800 text-sky-300'
        )}>
          {snap.state}
        </span>
      </div>

      {/* Classification */}
      <div className={clsx('border rounded-lg p-3', CC[classification_color] ?? CC['neutral'])}>
        <div className="text-[10px] uppercase tracking-wider mb-1 opacity-70">Final Classification</div>
        <div className="font-semibold text-sm">{classification}</div>
        <div className="text-xs mt-1 opacity-70">Scenario: {scenario_name}</div>
      </div>

      {/* Metrics grid */}
      <div className="grid grid-cols-2 gap-3">
        {[
          { label: 'Detection Time', value: fmtDuration(detection_time_seconds), desc: 'From normal to incident declared' },
          { label: 'Recovery Time', value: fmtDuration(recovery_time_seconds), desc: 'From mitigation to resolved' },
          { label: 'Peak Traffic', value: `${peaks.rps.toLocaleString(undefined, { maximumFractionDigits: 0 })} req/s`, desc: 'Maximum requests/sec observed' },
          { label: 'Peak CPU', value: fmt(peaks.cpu, '%'), desc: 'Maximum CPU utilisation' },
          { label: 'Peak Latency', value: peaks.latency_ms >= 1000 ? `${(peaks.latency_ms/1000).toFixed(1)}s` : `${Math.round(peaks.latency_ms)}ms`, desc: 'Maximum response latency' },
          { label: 'Peak Error Rate', value: fmt(peaks.error_rate, '%'), desc: 'Maximum request error rate' },
          { label: 'Min Availability', value: fmt(snap.availability, '%'), desc: 'Service availability at current reading' },
          { label: 'Peak Threat Score', value: `${peaks.threat_score.toFixed(0)} / 100`, desc: 'Demonstration model score' },
        ].map(({ label, value, desc }) => (
          <div key={label} className="bg-navy-800 border border-navy-700 rounded-lg p-3">
            <div className="text-[10px] text-slate-500 uppercase tracking-wider">{label}</div>
            <div className="text-lg font-bold font-mono text-white mt-1">{value}</div>
            <div className="text-[10px] text-slate-600 mt-0.5">{desc}</div>
          </div>
        ))}
      </div>

      {/* Disclaimer */}
      <div className="bg-navy-800/60 border border-navy-700 rounded px-3 py-2 text-[10px] text-slate-500">
        <strong className="text-slate-400">Academic Honesty Note:</strong> All values above are synthetic demonstration data.
        This simulation does not constitute an experimentally validated measurement of detection performance.
        Detection times, peak values, and classifications are generated by a demonstration model for educational purposes only.
      </div>
    </div>
  )
}
